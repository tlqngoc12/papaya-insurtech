package com.papaya.fraud.metrics;

import com.papaya.fraud.io.Json;
import com.papaya.fraud.metrics.MetricsResult.GroupRecall;
import com.papaya.fraud.metrics.MetricsResult.LegitScenario;
import com.papaya.fraud.metrics.MetricsResult.PatternRecall;
import com.papaya.fraud.metrics.MetricsResult.PrecisionAtK;
import com.papaya.fraud.metrics.MetricsResult.RulePrecision;
import com.papaya.fraud.metrics.ThresholdSelector.SweepRow;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.stream.Collectors;

/**
 * Renders {@code metrics_report.md} (O4) and {@code metrics.json} from a {@link MetricsResult}. Pure functions of their
 * inputs: same result and context, same bytes ({@code \n}, UTF-8 without BOM). Every number comes from the result.
 * Only the markdown carries the measured timings; metrics.json is identical across runs on the same data. Neither
 * contains a file path: inputs are named by file name (markdown) and SHA-256 (both).
 */
public final class MetricsReportWriter {

    static final double TARGET_RECALL = 0.70;
    static final double TARGET_FPR = 0.20;

    private MetricsReportWriter() {
    }

    public static byte[] markdownBytes(ReportContext ctx, MetricsResult r) {
        return markdown(ctx, r).getBytes(StandardCharsets.UTF_8);
    }

    public static byte[] jsonBytes(ReportContext ctx, MetricsResult r) {
        return Json.prettyBytes(json(ctx, r));
    }

    /** {@code threshold-sweep.json}: the confusion matrix and ratios for every T of the sweep. */
    public static byte[] sweepBytes(List<SweepRow> sweep, int selected) {
        Map<String, Object> doc = new LinkedHashMap<>();
        doc.put("rule", "predicted fraud when risk_score >= T; selected T has the highest recall among FPR <= 20%,"
                + " then the lowest FPR, then the largest T (S3)");
        doc.put("selected_threshold", selected);
        doc.put("rows", sweep.stream().map(row -> confusionJson(row.threshold(), row.confusion())).toList());
        return Json.prettyBytes(doc);
    }

    static String markdown(ReportContext ctx, MetricsResult r) {
        StringBuilder md = new StringBuilder();
        ConfusionMatrix c = r.confusion();
        line(md, "# Metrics report");
        line(md, "");
        line(md, "Generated by `evaluate`. Every number below is computed by the program from the files listed here.");
        line(md, "");
        line(md, "## Inputs");
        line(md, "");
        line(md, "| Item | Value |");
        line(md, "|---|---|");
        line(md, "| Seed | " + ctx.seed() + " |");
        line(md, "| Claims file | `" + ctx.claimsFileName() + "` |");
        line(md, "| Claims SHA-256 | `" + ctx.claimsSha256() + "` |");
        line(md, "| Config file | `" + ctx.configFileName() + "` |");
        line(md, "| Config SHA-256 | `" + ctx.configSha256() + "` |");
        line(md, "| Threshold T | " + r.threshold() + " |");
        line(md, "| Claims | " + (c.fraud() + c.legit()) + " (" + c.fraud() + " fraud, " + c.legit() + " legit) |");
        line(md, "");
        line(md, "## Definitions");
        line(md, "");
        line(md, "- A claim is **predicted fraud** when `risk_score >= T`.");
        line(md, "- **Precision** = TP / (TP + FP). **Recall** = TP / (TP + FN). **F1** = 2PR / (P + R).");
        line(md, "- **FPR (standard)** = FP / (FP + TN): false positives over all legit claims. This is the primary"
                + " reading of the challenge target (M1).");
        line(md, "- **FDR** = FP / (TP + FP) = 1 - precision: false positives over flagged claims. Reported because"
                + " the challenge's \"false positive rate\" can also be read this way.");
        line(md, "- **Recall by pattern**: claims of a fraud pattern that score at least T. *Flagged by own rule*"
                + " counts the claims of that pattern that carry the rule of the same name, whatever their score.");
        line(md, "- **Precision by rule**: over the claims carrying a flag of the rule (whatever their score), the share"
                + " that is fraud of any pattern, and the share that is fraud of the pattern of the same name.");
        line(md, "- **precision@k**: share of fraud among the top k claims of a ranking.");
        line(md, "");
        line(md, "## Confusion matrix at T = " + r.threshold());
        line(md, "");
        line(md, "| | Predicted fraud | Predicted legit |");
        line(md, "|---|---:|---:|");
        line(md, "| **Fraud** | TP = " + c.tp() + " | FN = " + c.fn() + " |");
        line(md, "| **Legit** | FP = " + c.fp() + " | TN = " + c.tn() + " |");
        line(md, "");
        line(md, "## Headline against the targets");
        line(md, "");
        line(md, "| Metric | Value | Target | Result |");
        line(md, "|---|---:|---|---|");
        line(md, "| Recall | " + pct(c.recall()) + " | >= 70% | " + verdict(c.recall() >= TARGET_RECALL) + " |");
        line(md, "| FPR (standard, FP / legit) | " + pct(c.fpr()) + " | <= 20% | "
                + verdict(c.fprAtMost(TARGET_FPR)) + " |");
        line(md, "| FDR (FP / flagged) | " + pct(c.fdr()) + " | <= 20% (alternative reading) | "
                + verdict(!Double.isNaN(c.fdr()) && c.fdr() <= TARGET_FPR) + " |");
        line(md, "| Precision | " + pct(c.precision()) + " | reported only (Q17) | |");
        line(md, "| F1 | " + pct(c.f1()) + " | reported only | |");
        line(md, "");
        line(md, "## Recall by rule group (L10)");
        line(md, "");
        line(md, "Reference-table rules share their tables or keys with the generator, so their recall is high by"
                + " construction; statistical rules are the ones that can genuinely miss.");
        line(md, "");
        line(md, "| Group | Patterns | Claims | Caught | Recall |");
        line(md, "|---|---|---:|---:|---:|");
        for (GroupRecall g : r.groups()) {
            line(md, "| " + g.group() + " | " + String.join(", ", g.patterns()) + " | " + g.claims() + " | "
                    + g.caught() + " | " + pct(g.recall()) + " |");
        }
        line(md, "");
        line(md, "## Recall by pattern");
        line(md, "");
        line(md, "| Pattern | Claims | Caught (score >= T) | Recall | Flagged by own rule |");
        line(md, "|---|---:|---:|---:|---:|");
        for (PatternRecall p : r.patterns()) {
            line(md, "| " + p.pattern() + " | " + p.claims() + " | " + p.caught() + " | " + pct(p.recall()) + " | "
                    + p.flaggedByOwnRule() + " |");
        }
        line(md, "");
        line(md, "## Precision by rule");
        line(md, "");
        line(md, "| Rule | Claims with flag | Fraud (any pattern) | Fraud (same pattern) | Precision (any) |"
                + " Precision (same pattern) |");
        line(md, "|---|---:|---:|---:|---:|---:|");
        for (RulePrecision p : r.rules()) {
            line(md, "| " + p.rule() + " | " + p.flagged() + " | " + p.fraudAnyPattern() + " | " + p.fraudSamePattern()
                    + " | " + pct(p.precisionAny()) + " | " + pct(p.precisionSamePattern()) + " |");
        }
        line(md, "");
        line(md, "## Legit claims flagged, by scenario");
        line(md, "");
        line(md, "`legit_noise` claims are planted to trigger a rule; `legit_near_miss` claims sit just outside a rule.");
        line(md, "");
        line(md, "| Label | Scenario | Claims | Score >= T | Flags carried (any score) |");
        line(md, "|---|---|---:|---:|---|");
        for (LegitScenario l : r.legit()) {
            line(md, "| " + l.label() + " | " + l.scenario() + " | " + l.claims() + " | " + l.flaggedAtThreshold()
                    + " | " + flags(l.flagsByRule()) + " |");
        }
        line(md, "");
        line(md, "## Ranking quality");
        line(md, "");
        line(md, "Engine ranking (configured weights, S5 tie-breaks) against the same flags re-scored with every weight"
                + " set to 1. Reported only; weights are not tuned on this.");
        line(md, "");
        line(md, "| k | precision@k (engine) | precision@k (all weights 1) |");
        line(md, "|---:|---:|---:|");
        for (PrecisionAtK p : r.ranking()) {
            line(md, "| " + p.k() + " | " + pct(p.engine()) + " (" + p.fraudEngine() + ") | " + pct(p.equalWeights())
                    + " (" + p.fraudEqualWeights() + ") |");
        }
        line(md, "");
        line(md, "## Rule coverage");
        line(md, "");
        line(md, "| Rule | Coverage |");
        line(md, "|---|---|");
        r.coverage().forEach((rule, values) -> line(md, "| " + rule + " | " + values.entrySet().stream()
                .map(e -> e.getKey() + " " + e.getValue()).collect(Collectors.joining(", ")) + " |"));
        line(md, "");
        line(md, "## Timing (varies from run to run)");
        line(md, "");
        line(md, "Measured wall-clock times of this run; they change on every run and are the only part of this report"
                + " that does. metrics.json carries no timings.");
        line(md, "");
        line(md, "| Step | Milliseconds |");
        line(md, "|---|---:|");
        line(md, "| Load claims.csv | " + ctx.loadMs() + " |");
        line(md, "| Score (index, 8 rules, rank) | " + ctx.scoreMs() + " |");
        line(md, "| Write scored_claims.json | " + ctx.writeMs() + " |");
        line(md, "");
        line(md, "## Limitations");
        line(md, "");
        line(md, "Read these numbers together with the known limitations: [docs/limitations.md](" + ctx.limitationsLink()
                + ").");
        return md.toString();
    }

    static Map<String, Object> json(ReportContext ctx, MetricsResult r) {
        Map<String, Object> doc = new LinkedHashMap<>();
        // Inputs are identified by content only: a path would differ between runs on the same data.
        Map<String, Object> inputs = new LinkedHashMap<>();
        inputs.put("seed", ctx.seed());
        inputs.put("claims_sha256", ctx.claimsSha256());
        inputs.put("config_sha256", ctx.configSha256());
        doc.put("inputs", inputs);
        doc.put("threshold", r.threshold());
        doc.put("confusion", confusionJson(r.threshold(), r.confusion()));
        Map<String, Object> targets = new LinkedHashMap<>();
        targets.put("recall_at_least_70", r.confusion().recall() >= TARGET_RECALL);
        targets.put("fpr_standard_at_most_20", r.confusion().fprAtMost(TARGET_FPR));
        targets.put("fdr_at_most_20", !Double.isNaN(r.confusion().fdr()) && r.confusion().fdr() <= TARGET_FPR);
        doc.put("targets", targets);
        doc.put("recall_by_group", r.groups().stream().map(g -> map("group", g.group(), "patterns", g.patterns(),
                "claims", g.claims(), "caught", g.caught(), "recall", num(g.recall()))).toList());
        doc.put("recall_by_pattern", r.patterns().stream().map(p -> map("pattern", p.pattern(), "claims", p.claims(),
                "caught", p.caught(), "recall", num(p.recall()), "flagged_by_own_rule", p.flaggedByOwnRule())).toList());
        doc.put("precision_by_rule", r.rules().stream().map(p -> map("rule", p.rule(), "flagged", p.flagged(),
                "fraud_any_pattern", p.fraudAnyPattern(), "fraud_same_pattern", p.fraudSamePattern(),
                "precision_any", num(p.precisionAny()), "precision_same_pattern", num(p.precisionSamePattern())))
                .toList());
        doc.put("legit_by_scenario", r.legit().stream().map(l -> map("label", l.label(), "scenario", l.scenario(),
                "claims", l.claims(), "flagged_at_threshold", l.flaggedAtThreshold(), "flags_by_rule", l.flagsByRule()))
                .toList());
        doc.put("precision_at_k", r.ranking().stream().map(p -> map("k", p.k(), "fraud_engine", p.fraudEngine(),
                "precision_engine", num(p.engine()), "fraud_equal_weights", p.fraudEqualWeights(),
                "precision_equal_weights", num(p.equalWeights()))).toList());
        doc.put("coverage", r.coverage());
        // No timings or other per-run values: metrics.json is byte-identical across runs on the same data.
        return doc;
    }

    static Map<String, Object> confusionJson(int threshold, ConfusionMatrix c) {
        return map("threshold", threshold, "tp", c.tp(), "fp", c.fp(), "fn", c.fn(), "tn", c.tn(),
                "precision", num(c.precision()), "recall", num(c.recall()), "fpr_standard", num(c.fpr()),
                "fdr", num(c.fdr()), "f1", num(c.f1()));
    }

    private static Map<String, Object> map(Object... keyValues) {
        Map<String, Object> m = new LinkedHashMap<>();
        for (int i = 0; i < keyValues.length; i += 2) {
            m.put((String) keyValues[i], keyValues[i + 1]);
        }
        return m;
    }

    /** NaN is not valid JSON: written as null. */
    private static Double num(double value) {
        return Double.isNaN(value) ? null : value;
    }

    static String pct(double value) {
        return Double.isNaN(value) ? "n/a" : String.format(Locale.US, "%.1f%%", value * 100);
    }

    private static String verdict(boolean pass) {
        return pass ? "PASS" : "FAIL";
    }

    private static String flags(Map<String, Integer> byRule) {
        if (byRule == null || byRule.isEmpty()) {
            return "none";
        }
        List<String> parts = new ArrayList<>();
        byRule.forEach((rule, n) -> parts.add(rule + " " + n));
        return String.join(", ", parts);
    }

    private static void line(StringBuilder md, String text) {
        md.append(text).append('\n');
    }
}
